#!/usr/bin/env python3
"""Generates the Postgres mirror schema (migrations/0002_mirror.sql) and the loader's table list (internal/loader/tables_gen.go)
from the SQLite schemas of the current system, so the two cannot drift. Usage: python3 tools/gen_schema.py <server/data dir>
Run again only when the SQLite schema changes (Phase 3 replaces the mirror with typed tables as ingestion is ported)."""
import sqlite3, sys, os
D = sys.argv[1].rstrip('/') + '/'
# (sqlite file, sqlite table, postgres schema.table)
MAP = [
 ('lumpad.db','activities','train.activity'),('lumpad.db','laps','train.lap'),('lumpad.db','gear','train.gear'),
 ('lumpad.db','health_daily','health.daily'),('lumpad.db','fitness_daily','health.fitness_daily'),
 ('lumpad.db','raw_pulls','raw.pull'),('lumpad.db','sync_runs','raw.sync_run'),('lumpad.db','sync_jobs','raw.sync_job'),
 ('coros.db','activities','raw.coros_activity'),('coros.db','fit_files','raw.fit_file'),('coros.db','responses','raw.response'),
 ('coros.db','tasks','raw.archive_task'),('coros.db','usage','raw.archive_usage'),('coros.db','limits','raw.archive_limit'),('coros.db','meta','raw.archive_meta'),
 ('intel.db','fit_session','train.session_metric'),('intel.db','run_weather','train.run_weather'),('intel.db','weather_cache','train.weather_cache'),
 ('intel.db','daily_feat','analytics.daily_feat'),('intel.db','daily_log','health.checkin'),('intel.db','twin_state','athlete.state_snapshot'),
 ('intel.db','athlete_baseline','athlete.baseline'),('intel.db','corr_edge','analytics.corr_edge'),('intel.db','kb_docs','memory.kb_doc'),('intel.db','intel_job','analytics.intel_job'),
 ('memory.db','memory','memory.item'),('memory.db','memory_audit','memory.audit'),('memory.db','coach_run','coach.run'),('memory.db','balance_snap','coach.balance_snap'),
 ('memory.db','coach_job','coach.job_ledger'),
]
PGT = {'INTEGER':'BIGINT','REAL':'DOUBLE PRECISION','TEXT':'TEXT','BLOB':'BYTEA'}
DATECOLS = {'date','day'}          # ISO yyyy-mm-dd text → DATE (needed for hypertables and range queries)
sql = ['-- GENERATED by tools/gen_schema.py from the SQLite schemas — the Phase 1 mirror of today\'s data. Do not edit by hand.']
go = ['// Code generated by tools/gen_schema.py; DO NOT EDIT.', 'package loader', '', 'var Tables = []Table{']
# the newer coach_job table does not exist in older data; give the generator its definition
EXTRA = {('memory.db','coach_job'): [('key','TEXT',1),('intent','TEXT',0),('attempts','INTEGER',0),('next_try','TEXT',0),('last_error','TEXT',0),('status','TEXT',0),('updated_at','TEXT',0)]}
seen_schemas = set()
for f, t, dst in MAP:
    cols = None
    if os.path.exists(D+f):
        c = sqlite3.connect(f'file:{D}{f}?mode=ro', uri=True)
        info = c.execute(f'pragma table_info({t})').fetchall()
        if info: cols = [(r[1], (r[2] or 'TEXT').upper(), r[5]) for r in info]
    if cols is None: cols = EXTRA.get((f, t))
    if cols is None: print('skip (no table)', f, t); continue
    pk = sorted([c for c in cols if c[2]], key=lambda c: c[2])
    ddl = []
    for n, ty, p in cols:
        pgty = 'DATE' if n in DATECOLS and ty == 'TEXT' else PGT[ty]
        ddl.append(f'  "{n}" {pgty}' + (' NOT NULL' if p else ''))
    if pk: ddl.append('  PRIMARY KEY (' + ', '.join(f'"{c[0]}"' for c in pk) + ')')
    sql.append(f'CREATE TABLE {dst} (\n' + ',\n'.join(ddl) + '\n);')
    kinds = []
    for n, ty, p in cols:
        k = 'date' if n in DATECOLS and ty == 'TEXT' else {'INTEGER':'int','REAL':'float','TEXT':'text','BLOB':'blob'}[ty]
        kinds.append(f'{{"{n}", "{k}"}}')
    order = ', '.join(f'"{c[0]}"' for c in pk) or '"rowid"'
    go.append(f'\t{{Src: "{f}", SrcTable: "{t}", Dst: "{dst}", Cols: []Col{{{", ".join(kinds)}}}, PK: []string{{{", ".join(chr(34)+c[0]+chr(34) for c in pk)}}}}},')
go.append('}')
open('migrations_0002.tmp','w').write('\n\n'.join(sql)+'\n')
os.replace('migrations_0002.tmp','internal/db/migrations/0002_mirror.sql')
open('internal/loader/tables_gen.go','w').write('\n'.join(go)+'\n')
print('tables:', len(MAP))
