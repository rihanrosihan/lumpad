//go:build ignore

// Generates fts5_tables.go from /tmp/fts5_probe.json (tools/probe_fts5_unicode.mjs): the code points FTS5's unicode61 tokenizer treats as
// token characters (as ranges) and the characters whose FTS5 folding differs from NFD + remove marks + simple lower-casing.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"golang.org/x/text/unicode/norm"
)

// the same rule as foldRune in bm25.go
func goFold(r rune) string {
	d := []rune(norm.NFD.String(string(r)))
	if len(d) > 1 {
		only := true
		for _, c := range d[1:] {
			if !unicode.Is(unicode.Mn, c) {
				only = false
			}
		}
		if only && !unicode.Is(unicode.Mn, d[0]) {
			r = d[0]
		}
	}
	return string(unicode.ToLower(r))
}

func main() {
	b, _ := os.ReadFile("/tmp/fts5_probe.json")
	var p struct {
		Ranges [][2]int
		Fold   map[string]string
	}
	if err := json.Unmarshal(b, &p); err != nil {
		panic(err)
	}
	var keys []int
	exc := map[int]string{}
	for k, v := range p.Fold {
		cp, _ := strconv.Atoi(k)
		if goFold(rune(cp)) != v {
			exc[cp] = v
			keys = append(keys, cp)
		}
	}
	sort.Ints(keys)
	var out strings.Builder
	out.WriteString("// Code generated by gen_fts5.go from the real FTS5 tokenizer (tools/probe_fts5_unicode.mjs); DO NOT EDIT.\npackage coach\n\n")
	out.WriteString("// fts5TokenRanges: code points >= 0x80 that FTS5 unicode61 treats as token characters (everything else separates).\nvar fts5TokenRanges = [][2]rune{\n")
	for _, r := range p.Ranges {
		fmt.Fprintf(&out, "\t{0x%X, 0x%X},\n", r[0], r[1])
	}
	out.WriteString("}\n\n// fts5FoldExceptions: token characters whose FTS5 folding differs from NFD + marks removed + simple lower-casing.\nvar fts5FoldExceptions = map[rune]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&out, "\t0x%X: %q,\n", k, exc[k])
	}
	out.WriteString("}\n")
	if err := os.WriteFile("fts5_tables.go", []byte(out.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Println("token ranges:", len(p.Ranges), "fold exceptions:", len(keys))
}
